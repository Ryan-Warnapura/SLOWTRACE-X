"""Render the challenge-target thumbnails used on the Mission page.

Reads the recorded SPHEREx cutouts bundled in public/ and writes two native
resolution, lossless WebP images per target (an early and a late epoch on a
shared stretch) plus src/mission/targetPlates.ts describing them. The pixels
are the archive pixels; only the display stretch is applied, matching the
grayscale palette in src/lib.ts. Requires Pillow.

    python scripts/render_target_plates.py
"""

from __future__ import annotations

import json
import math
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
TARGETS = [
    ("barnard", "starter.json", (1, 5)),
    ("epsindib", "examples/epsindib.json", (0, 1)),
    ("wise0855", "examples/wise0855.json", (0, 1)),
    ("rwaur", "examples/rwaur.json", (0, 1)),
    ("rdra", "examples/rdra.json", (0, 1)),
]


def quantile(values: list[float], p: float) -> float:
    ordered = sorted(values)
    return ordered[min(len(ordered) - 1, max(0, math.floor((len(ordered) - 1) * p)))]


def render(frame: dict, lo: float, hi: float) -> Image.Image:
    image = Image.new("L", (frame["width"], frame["height"]))
    pixels = []
    for value in frame["data"]:
        if value is None:
            pixels.append(0)
            continue
        t = max(0.0, min(1.0, (value - lo) / ((hi - lo) or 1)))
        pixels.append(round(255 * math.asinh(t * 12) / math.asinh(12)))
    image.putdata(pixels)
    return image


def main() -> None:
    out = ROOT / "public" / "images" / "targets"
    out.mkdir(parents=True, exist_ok=True)
    plates = []
    for slug, path, picks in TARGETS:
        frames = json.loads((ROOT / "public" / path).read_text())["frames"]
        chosen = [frames[i] for i in picks]
        valid = [v for f in chosen for v in f["data"] if v is not None]
        lo, hi = quantile(valid, 0.02), quantile(valid, 0.995)
        epochs = []
        for label, frame in zip("ab", chosen):
            name = f"{slug}-{label}.webp"
            render(frame, lo, hi).save(out / name, lossless=True, method=6)
            meta = frame["metadata"]
            epochs.append(
                {
                    "src": f"/images/targets/{name}",
                    "date": meta["date"][:10],
                    "wavelength": round(meta.get("wavelengthCenter") or 0, 3),
                    "detector": meta["detector"],
                }
            )
        plates.append({"slug": slug, "epochs": epochs, "count": len(frames)})
    body = json.dumps(plates, indent=2)
    target = ROOT / "src" / "mission" / "targetPlates.ts"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(
        "// Generated by scripts/render_target_plates.py from the recorded cutouts in public/.\n"
        "export type TargetPlate = {\n"
        "  slug: string;\n"
        "  count: number;\n"
        "  epochs: { src: string; date: string; wavelength: number; detector: number }[];\n"
        "};\n"
        f"export const TARGET_PLATES: TargetPlate[] = {body};\n"
    )


if __name__ == "__main__":
    main()
